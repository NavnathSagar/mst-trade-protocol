const { ethers } = require("ethers");
const fs = require("fs");
const path = require("path");
require("dotenv").config({ path: ".env.local" });

async function main() {
  const isMainnet = process.argv.includes("--mainnet");
  const rpcUrl = isMainnet
    ? "https://mariorpc.mstblockchain.com/"
    : "https://testnetrpc.mstblockchain.com";
  const networkName = isMainnet ? "MST Mainnet (4646)" : "MST Testnet (91562037)";
  const explorerUrl = isMainnet ? "https://mstscan.com" : "https://testnet.mstscan.com";

  if (!process.env.PRIVATE_KEY) {
    throw new Error("❌ Missing PRIVATE_KEY in .env.local!");
  }

  const provider = new ethers.JsonRpcProvider(rpcUrl);
  const wallet = new ethers.Wallet(process.env.PRIVATE_KEY, provider);

  console.log(`🚀 Deploying MSTTradeProtocol to ${networkName}`);
  console.log(`👤 Deployer Wallet: ${wallet.address}`);

  const balance = await provider.getBalance(wallet.address);
  console.log(`💰 Account Balance: ${ethers.formatEther(balance)} ${isMainnet ? "MSTC" : "tMSTC"}`);

  // Read compiled artifact generated by `npx hardhat compile`
  const artifactPath = path.join(
    __dirname,
    "../artifacts/contracts/MSTTradeProtocol.sol/MSTTradeProtocol.json"
  );
  const artifact = JSON.parse(fs.readFileSync(artifactPath, "utf8"));

  const factory = new ethers.ContractFactory(artifact.abi, artifact.bytecode, wallet);
  const contract = await factory.deploy(wallet.address);

  console.log("⏳ Waiting for deployment confirmation on MST Blockchain...");
  await contract.waitForDeployment();

  const deployedAddress = await contract.getAddress();
  const deployTx = contract.deploymentTransaction();

  console.log("==================================================");
  console.log("✅ MSTTradeProtocol Deployed Successfully!");
  console.log("📍 Contract Address:", deployedAddress);
  console.log("🔗 Deployment Tx Hash:", deployTx ? deployTx.hash : "N/A");
  console.log(`🔍 Verify on MSTScan: ${explorerUrl}/address/${deployedAddress}`);
  console.log("==================================================");
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});